CREATE TABLE DinhMuc (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, revision INT UNSIGNED NOT NULL,
 output_qty_base DECIMAL(20,6) NOT NULL, wastage_percent DECIMAL(20,6) NOT NULL DEFAULT 0,
 effective_from DATE NOT NULL, effective_to DATE NULL, created_by_id BIGINT UNSIGNED NOT NULL,
 UNIQUE(product_id,revision), UNIQUE(id,product_id), CHECK(output_qty_base>0), CHECK(wastage_percent=0),
 CHECK(effective_to IS NULL OR effective_to>=effective_from),
 FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT, FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ChiTietDinhMuc (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, bom_id BIGINT UNSIGNED NOT NULL, material_id BIGINT UNSIGNED NOT NULL,
 unit_id BIGINT UNSIGNED NOT NULL, qty_per_output DECIMAL(20,6) NOT NULL, UNIQUE(bom_id,material_id), CHECK(qty_per_output>0),
 FOREIGN KEY(bom_id) REFERENCES DinhMuc(id) ON DELETE RESTRICT, FOREIGN KEY(material_id) REFERENCES NguyenLieu(id) ON DELETE RESTRICT,
 FOREIGN KEY(unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE LichNangLucXuong (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, workshop_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 business_date DATE NOT NULL, capacity_base DECIMAL(20,6) NOT NULL, UNIQUE(workshop_id,product_id,business_date), CHECK(capacity_base>=0),
 FOREIGN KEY(workshop_id) REFERENCES XuongSanXuat(id) ON DELETE RESTRICT, FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE DonHang (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 customer_id BIGINT UNSIGNED NOT NULL, due_date DATE NOT NULL, delivery_address VARCHAR(1000) NOT NULL,
 recipient VARCHAR(255) NOT NULL, recipient_phone VARCHAR(32) NOT NULL,
 status ENUM('NHAP','XAC_NHAN','DANG_GIAO','DA_GIAO','HUY') NOT NULL DEFAULT 'NHAP', currency CHAR(3) NOT NULL DEFAULT 'VND',
 total_amount DECIMAL(20,0) NULL, rounding_revision VARCHAR(50) NULL, version INT UNSIGNED NOT NULL DEFAULT 0,
 created_by_id BIGINT UNSIGNED NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CHECK(currency='VND'), CHECK(total_amount IS NULL OR total_amount>=0), INDEX(customer_id,created_at), INDEX(status,due_date),
 FOREIGN KEY(customer_id) REFERENCES KhachHang(id) ON DELETE RESTRICT, FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ChiTietDonHang (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, line_no INT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL, unit_id BIGINT UNSIGNED NOT NULL, packaging_id BIGINT UNSIGNED NOT NULL,
 qty_input DECIMAL(20,6) NOT NULL, factor_snapshot DECIMAL(20,9) NOT NULL, qty_base DECIMAL(20,6) NOT NULL,
 price_id BIGINT UNSIGNED NULL, unit_price DECIMAL(20,6) NULL, amount DECIMAL(20,0) NULL,
 UNIQUE(order_id,line_no), UNIQUE(id,order_id), CHECK(qty_input>0 AND qty_base>0 AND factor_snapshot>0),
 CHECK(unit_price IS NULL OR unit_price>=0), CHECK(amount IS NULL OR amount>=0),
 FOREIGN KEY(order_id) REFERENCES DonHang(id) ON DELETE RESTRICT, FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT,
 FOREIGN KEY(unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT,
 FOREIGN KEY(packaging_id,product_id) REFERENCES QuyCachDongGoi(id,product_id) ON DELETE RESTRICT,
 FOREIGN KEY(price_id) REFERENCES GiaBanThanhPham(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE KeHoachSanXuat (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE, order_id BIGINT UNSIGNED NOT NULL,
 start_date DATE NOT NULL, end_date DATE NOT NULL,
 status ENUM('CHO_DUYET','DA_DUYET','TU_CHOI','DANG_THUC_HIEN','HOAN_THANH','HUY') NOT NULL DEFAULT 'CHO_DUYET',
 approver_id BIGINT UNSIGNED NULL, decided_at DATETIME(3) NULL, rejection_reason VARCHAR(1000) NULL,
 version INT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CHECK(start_date<=end_date), INDEX(order_id,status),
 FOREIGN KEY(order_id) REFERENCES DonHang(id) ON DELETE RESTRICT, FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT,
 FOREIGN KEY(approver_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ChiTietKeHoachSanXuat (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, plan_id BIGINT UNSIGNED NOT NULL, order_line_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL, workshop_id BIGINT UNSIGNED NOT NULL, bom_version_id BIGINT UNSIGNED NOT NULL,
 qty_base DECIMAL(20,6) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 CHECK(qty_base>0), CHECK(start_date<=end_date), INDEX(order_line_id),
 FOREIGN KEY(plan_id) REFERENCES KeHoachSanXuat(id) ON DELETE RESTRICT, FOREIGN KEY(order_line_id) REFERENCES ChiTietDonHang(id) ON DELETE RESTRICT,
 FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT, FOREIGN KEY(workshop_id) REFERENCES XuongSanXuat(id) ON DELETE RESTRICT,
 FOREIGN KEY(bom_version_id,product_id) REFERENCES DinhMuc(id,product_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE PhanBoLichSanXuat (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, plan_line_id BIGINT UNSIGNED NOT NULL, calendar_id BIGINT UNSIGNED NOT NULL,
 qty_base DECIMAL(20,6) NOT NULL, UNIQUE(plan_line_id,calendar_id), CHECK(qty_base>0),
 FOREIGN KEY(plan_line_id) REFERENCES ChiTietKeHoachSanXuat(id) ON DELETE RESTRICT, FOREIGN KEY(calendar_id) REFERENCES LichNangLucXuong(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE NhuCauNguyenLieuKHSX (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, plan_line_id BIGINT UNSIGNED NOT NULL, bom_line_id BIGINT UNSIGNED NOT NULL,
 material_id BIGINT UNSIGNED NOT NULL, unit_id BIGINT UNSIGNED NOT NULL, qty_required DECIMAL(20,6) NOT NULL,
 snapshot_available DECIMAL(20,6) NOT NULL DEFAULT 0, shortage DECIMAL(20,6) NOT NULL, policy_revision VARCHAR(50) NOT NULL,
 UNIQUE(plan_line_id,material_id), CHECK(qty_required>=0 AND snapshot_available>=0 AND shortage>=0),
 FOREIGN KEY(plan_line_id) REFERENCES ChiTietKeHoachSanXuat(id) ON DELETE RESTRICT, FOREIGN KEY(bom_line_id) REFERENCES ChiTietDinhMuc(id) ON DELETE RESTRICT,
 FOREIGN KEY(material_id) REFERENCES NguyenLieu(id) ON DELETE RESTRICT, FOREIGN KEY(unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE DonMuaNguyenLieu (
