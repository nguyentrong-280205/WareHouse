 CHECK(currency='VND'), CHECK(total_amount IS NULL OR total_amount>=0), INDEX(plan_id,status), INDEX(supplier_id,status),
 FOREIGN KEY(plan_id) REFERENCES KeHoachSanXuat(id) ON DELETE RESTRICT, FOREIGN KEY(supplier_id) REFERENCES NhaCungCap(id) ON DELETE RESTRICT,
