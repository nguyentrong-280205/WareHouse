-- Additive schema for UC10/25/19/20/30 and FS02/05/11. Existing data/history are untouched.
CREATE TABLE DonViTinh (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, dimension ENUM('COUNT','MASS','VOLUME','CAPACITY_VOLUME') NOT NULL,
 discrete BOOLEAN NOT NULL, scale TINYINT UNSIGNED NOT NULL, CHECK(scale<=6), CHECK(NOT discrete OR scale=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE NguyenLieu (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, base_unit_id BIGINT UNSIGNED NOT NULL, requires_expiry BOOLEAN NOT NULL,
 storage_condition VARCHAR(1000) NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE',
 version INT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(base_unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ThanhPham (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, base_unit_id BIGINT UNSIGNED NOT NULL, container_type ENUM('PET','GLASS','CAN') NOT NULL,
 volume_ml DECIMAL(20,6) NOT NULL, shelf_life_days INT UNSIGNED NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE',
 version INT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CHECK(volume_ml>0), CHECK(shelf_life_days IS NULL OR shelf_life_days>0),
 FOREIGN KEY(base_unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT, FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE QuyCachDongGoi (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, unit_id BIGINT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL, units_per_pack DECIMAL(20,9) NOT NULL, effective_from DATE NOT NULL,
 created_by_id BIGINT UNSIGNED NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(product_id,unit_id,revision), UNIQUE(id,product_id), CHECK(units_per_pack>0), CHECK(revision>0),
 FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT, FOREIGN KEY(unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE GiaBanThanhPham (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, unit_id BIGINT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL, unit_price DECIMAL(20,6) NOT NULL, effective_at DATETIME(3) NOT NULL,
 created_by_id BIGINT UNSIGNED NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(product_id,unit_id,revision), CHECK(unit_price>=0), CHECK(revision>0), INDEX(product_id,unit_id,effective_at),
 FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT, FOREIGN KEY(unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE Kho (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
 type ENUM('MATERIAL','FINISHED','CONTROLLED') NOT NULL, capacity DECIMAL(20,6) NOT NULL, capacity_unit_id BIGINT UNSIGNED NOT NULL,
 status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE', version INT UNSIGNED NOT NULL DEFAULT 0,
 created_by_id BIGINT UNSIGNED NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), CHECK(capacity>=0),
 FOREIGN KEY(capacity_unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT, FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE ViTriLuuKho (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, warehouse_id BIGINT UNSIGNED NOT NULL, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL,
 name VARCHAR(255) NOT NULL, area VARCHAR(255) NULL, capacity DECIMAL(20,6) NOT NULL, capacity_unit_id BIGINT UNSIGNED NOT NULL,
 storage_rule VARCHAR(1000) NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE', version INT UNSIGNED NOT NULL DEFAULT 0,
 lock_generation BIGINT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(warehouse_id,code), UNIQUE(id,warehouse_id), CHECK(capacity>=0),
 FOREIGN KEY(warehouse_id) REFERENCES Kho(id) ON DELETE RESTRICT, FOREIGN KEY(capacity_unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE TaiKhoan_Kho (
 account_id BIGINT UNSIGNED NOT NULL, warehouse_id BIGINT UNSIGNED NOT NULL, PRIMARY KEY(account_id,warehouse_id),
 FOREIGN KEY(account_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT, FOREIGN KEY(warehouse_id) REFERENCES Kho(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE XuongSanXuat (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE TaiKhoan_Xuong (
 account_id BIGINT UNSIGNED NOT NULL, workshop_id BIGINT UNSIGNED NOT NULL, PRIMARY KEY(account_id,workshop_id),
 FOREIGN KEY(account_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT, FOREIGN KEY(workshop_id) REFERENCES XuongSanXuat(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE NhaCungCap (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL, address TEXT NULL, phone VARCHAR(32) NULL, email VARCHAR(255) NULL,
 status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE LoNguyenLieu (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL,
 material_id BIGINT UNSIGNED NOT NULL, manufactured_on DATE NOT NULL, expires_on DATE NULL,
 first_received_at DATETIME(3) NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE',
 version INT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(material_id,code), CHECK(expires_on IS NULL OR expires_on>=manufactured_on),
 INDEX(material_id,expires_on,first_received_at), FOREIGN KEY(material_id) REFERENCES NguyenLieu(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE LoThanhPham (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL, packaging_version_id BIGINT UNSIGNED NOT NULL, manufactured_on DATE NOT NULL, expires_on DATE NOT NULL,
 first_received_at DATETIME(3) NULL, status ENUM('ACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE',
 version INT UNSIGNED NOT NULL DEFAULT 0, created_by_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(product_id,code), CHECK(expires_on>=manufactured_on), INDEX(product_id,expires_on,first_received_at),
 FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT,
 FOREIGN KEY(packaging_version_id,product_id) REFERENCES QuyCachDongGoi(id,product_id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by_id) REFERENCES TaiKhoan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE HeSoChiemCho (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, material_id BIGINT UNSIGNED NULL, product_id BIGINT UNSIGNED NULL,
 capacity_unit_id BIGINT UNSIGNED NOT NULL, revision INT UNSIGNED NOT NULL, factor_per_base DECIMAL(20,9) NOT NULL,
 effective_at DATETIME(3) NOT NULL, item_kind VARCHAR(8) GENERATED ALWAYS AS (IF(material_id IS NULL,'PRODUCT','MATERIAL')) STORED,
 item_key BIGINT UNSIGNED GENERATED ALWAYS AS (COALESCE(material_id,product_id)) STORED,
 UNIQUE(item_kind,item_key,capacity_unit_id,revision), CHECK((material_id IS NULL)<>(product_id IS NULL)), CHECK(factor_per_base>0),
 FOREIGN KEY(material_id) REFERENCES NguyenLieu(id) ON DELETE RESTRICT, FOREIGN KEY(product_id) REFERENCES ThanhPham(id) ON DELETE RESTRICT,
 FOREIGN KEY(capacity_unit_id) REFERENCES DonViTinh(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
